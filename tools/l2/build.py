# -*- coding: utf-8 -*-
"""Level 2 app content: merges tools/l2/out/*.json (written as [it, fr, en, es]) into app/l2/content.js.
The app keeps [it, fr, en] arrays (same engine as Level 3); Spanish and Argentine Spanish go into
window.TWG_ESX = {es: {en: es}, ar: {en: es-ar}}, merged by the app into its display translator.
Run from the repo root:  python3 tools/l2/build.py"""
import json, glob, hashlib, os, re, sys, subprocess
sys.path.insert(0, 'tools/i18n'); from ar_rules import to_ar

S = json.loads(subprocess.run(['node', '-e', 'global.window={};require("./app/l2/structure.js");console.log(JSON.stringify(window.TWG_L2))'],
                              capture_output=True, text=True, check=True).stdout)
ORDER = [c for g in S['groups'] for c in g['c']]
bank, lessons, flash, es, ar = [], [], [], {}, {}
seen = set()

def tri(a, where):
    assert isinstance(a, list) and len(a) == 4 and all(isinstance(x, str) and x.strip() for x in a), where
    en, sp = a[2].strip(), a[3].strip()
    if en in es and es[en] != sp: pass  # first translation wins
    else: es[en] = sp
    v = to_ar(sp)
    if v and v != sp: ar[en] = v
    return [a[0].strip(), a[1].strip(), en]

for f in sorted(glob.glob('tools/l2/out/*.json')):
    D = json.load(open(f, encoding='utf8')); src = os.path.basename(f)
    for i, L in enumerate(D.get('lessons', [])):
        assert L['c'] in S['chapters'], (src, L['c'])
        lessons.append({'c': L['c'], 't': tri(L['t'], src), 'p': [tri(p, src) for p in L['p']], 'k': [tri(k, src) for k in L.get('keys', [])]})
    for q in D.get('questions', []):
        assert q['c'] in S['chapters'] and len(q['o']) == 4, (src, q.get('c'))
        key = q['q'][2].strip().lower()
        if key in seen: continue
        seen.add(key)
        qid = 'l2' + hashlib.md5((q['c'] + key).encode()).hexdigest()[:7]
        bank.append({'id': qid, 'c': q['c'], 'p': 0, 'q': tri(q['q'], src), 'o': [tri(o, src) for o in q['o']], 'e': tri(q['e'], src), 'd': tri(q['d'], src)})
    for x in D.get('flash', []):
        assert x['c'] in S['chapters'], (src, x['c'])
        flash.append({'c': x['c'], 'f': tri(x['f'], src), 'b': tri(x['b'], src)})

rank = {c: i for i, c in enumerate(ORDER)}
bank.sort(key=lambda b: rank[b['c']]); lessons.sort(key=lambda b: rank[b['c']]); flash.sort(key=lambda b: rank[b['c']])
ch = {c: {'it': v['n']['it'], 'fr': v['n']['fr'], 'en': v['n']['en']} for c, v in S['chapters'].items()}
for c, v in S['chapters'].items(): es[v['n']['en']] = v['n']['es']
groups = [{'k': g['k'], 'w': g['w'], 'n': {l: g['n'][l] for l in ('it', 'fr', 'en')}, 'c': g['c']} for g in S['groups']]
for g in S['groups']: es[g['n']['en']] = g['n']['es']
for k, v in list(es.items()):
    a = to_ar(v)
    if a and a != v: ar[k] = a
out = {'level': 2, 'exam': S['exam'], 'ch': ch, 'groups': groups, 'bank': bank, 'lessons': lessons, 'flash': flash}
js = '/* generated by tools/l2/build.py — do not edit */\nwindow.TWG_L2C=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + \
     ';\nwindow.TWG_ESX=' + json.dumps({'es': es, 'ar': ar}, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('app/l2/content.js', 'w', encoding='utf8').write(js)
h = hashlib.md5((js + open('app/l2/l2app.js', encoding='utf8').read()).encode()).hexdigest()[:8]
ix = open('app/index.html', encoding='utf8').read()
ix = re.sub(r'l2/content\.js\?v=[\w]+', 'l2/content.js?v=' + h, ix); ix = re.sub(r'l2/l2app\.js\?v=[\w]+', 'l2/l2app.js?v=' + h, ix)
open('app/index.html', 'w', encoding='utf8').write(ix)
from collections import Counter
cq = Counter(b['c'] for b in bank)
print(len(bank), 'questions,', len(lessons), 'lessons,', len(flash), 'flashcards;', round(len(js) / 1024), 'KB')
print('missing chapters:', [c for c in ORDER if not cq[c]])
