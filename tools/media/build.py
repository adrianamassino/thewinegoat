# -*- coding: utf-8 -*-
"""Podcasts + films for a level that uses the shared Level 1/2 screens.
Reads tools/media/out/<lv>_*.json (pods) and tools/media/out/<lv>_films.js (films), writes <dir>/podtext/<lang>.json and
<dir>/media.js (window.TWG_MEDIA). Recorded audio, if present in <dir>/pods/<lang>/<id>.mp3 with <id>.json timings
({"d":seconds,"T":[paragraph starts]}), is declared so the app plays it; otherwise the device voice reads the text.
Run from the repo root:  python3 tools/media/build.py s1   (levels: l1 l2 s1 s2 s3)"""
import json, glob, os, sys, hashlib, re
LV = sys.argv[1]; DIR = {'l1': 'app/l1/', 'l2': 'app/l2/'}.get(LV, f'app/spirits/{LV}/'); BASE = DIR[4:]
st = json.loads(os.popen(f'node -e \'global.window={{}};require("./{DIR}structure.js");const k=Object.keys(window).find(k=>/^TWG_/.test(k));console.log(JSON.stringify(window[k]))\'').read())
order = [c for g in st['groups'] for c in g['c']]
pods = []
for f in sorted(glob.glob(f'tools/media/out/{LV}_*.json')):
    pods += json.load(open(f, encoding='utf8'))['pods']
pods.sort(key=lambda p: order.index(p['c']) if p['c'] in order else 99)
meta, text = [], {'it': {}, 'fr': {}, 'en': {}}
for n, p in enumerate(pods, 1):
    pid = f'{LV}p{n:02d}'
    m = {'id': pid, 'n': n, 'c': p['c'], 't': p['t'], 'd': {}, 'T': {}}
    for lg in text:
        text[lg][pid] = {'p': p['p'][lg]}
        tj = f'{DIR}pods/{lg}/{pid}.json'
        if os.path.exists(tj) and os.path.exists(f'{DIR}pods/{lg}/{pid}.mp3'):
            j = json.load(open(tj)); m['d'][lg] = j['d']; m['T'][lg] = j['T']
    meta.append(m)
if pods:
    os.makedirs(DIR + 'podtext', exist_ok=True)
    for lg, d in text.items(): json.dump(d, open(f'{DIR}podtext/{lg}.json', 'w', encoding='utf8'), ensure_ascii=False, separators=(',', ':'))
films = '\n'.join(open(f, encoding='utf8').read() for f in sorted(glob.glob(f'tools/media/out/{LV}_films*.js')))
js = f'/* generated by tools/media/build.py — do not edit */\n{films}\nwindow.TWG_MEDIA=window.TWG_MEDIA||{{}};TWG_MEDIA.base={json.dumps(BASE)};TWG_MEDIA.pods={json.dumps(meta, ensure_ascii=False, separators=(",", ":"))};\n'
open(DIR + 'media.js', 'w', encoding='utf8').write(js)
h = hashlib.md5(js.encode()).hexdigest()[:8]
ix = open('app/index.html', encoding='utf8').read(); ix = re.sub(r"media\.js\?v=\w+", 'media.js?v=' + h, ix); open('app/index.html', 'w', encoding='utf8').write(ix)
print(LV, len(meta), 'podcasts,', films.count('{id:'), 'films;', round(len(js) / 1024), 'KB media.js;', sum(1 for m in meta for lg in m['d']), 'recorded audio files')
