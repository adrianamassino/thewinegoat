# -*- coding: utf-8 -*-
"""Spirits app content: merges tools/spirits/<lv>/out/*.json (written as [it, fr, en, es]) into app/spirits/<lv>/content.js
(window.TWG_S1C / TWG_S2C / TWG_S3C);
also Sake 1 (k1: tools/sake/k1/out -> app/sake/k1/content.js, TWG_K1C) and Beer 1 (b1: tools/beer/b1/out -> app/beer/b1/content.js, TWG_B1C). Same data shape as the wine Level 1-2 content, plus track:"spirits", so the
shared l2app.js screens and the main quiz engine work unchanged. Spanish and Argentine Spanish go into window.TWG_ESX.
Run from the repo root:  python3 tools/spirits/build.py s1"""
import json, glob, hashlib, os, re, sys, subprocess
sys.path.insert(0, 'tools/i18n'); from ar_rules import to_ar
LV = sys.argv[1] if len(sys.argv) > 1 else 's1'; N = LV.upper()
TRACK = {'s': 'spirits', 'k': 'sake', 'b': 'beer'}[LV[0]]
S = json.loads(subprocess.run(['node', '-e', f'global.window={{}};require("./app/{TRACK}/{LV}/structure.js");console.log(JSON.stringify(window.TWG_{N}))'],
                              capture_output=True, text=True, check=True).stdout)
ORDER = [c for g in S['groups'] for c in g['c']]
bank, lessons, flash, es, ar, seen = [], [], [], {}, {}, set()

def tri(a, where):
    assert isinstance(a, list) and len(a) == 4 and all(isinstance(x, str) and x.strip() for x in a), (where, a)
    en, sp = a[2].strip(), a[3].strip()
    es.setdefault(en, sp)
    v = to_ar(sp)
    if v and v != sp: ar.setdefault(en, v)
    return [a[0].strip(), a[1].strip(), en]

for f in sorted(glob.glob(f'tools/{TRACK}/{LV}/out/*.json')):
    D = json.load(open(f, encoding='utf8')); src = os.path.basename(f)
    for L in D.get('lessons', []):
        assert L['c'] in S['chapters'], (src, L['c'])
        lessons.append({'c': L['c'], 't': tri(L['t'], src), 'p': [tri(p, src) for p in L['p']], 'k': [tri(k, src) for k in L.get('keys', [])]})
    for q in D.get('questions', []):
        assert q['c'] in S['chapters'] and len(q['o']) == 4, (src, q.get('c'))
        key = q['q'][2].strip().lower()
        if key in seen: continue
        seen.add(key)
        qid = LV + hashlib.md5((q['c'] + key).encode()).hexdigest()[:7]
        bank.append({'id': qid, 'c': q['c'], 'p': 0, 'q': tri(q['q'], src), 'o': [tri(o, src) for o in q['o']], 'e': tri(q['e'], src), 'd': tri(q['d'], src)})
    for x in D.get('flash', []):
        assert x['c'] in S['chapters'], (src, x['c'])
        flash.append({'c': x['c'], 'f': tri(x['f'], src), 'b': tri(x['b'], src)})

rank = {c: i for i, c in enumerate(ORDER)}
for a in (bank, lessons, flash): a.sort(key=lambda b: rank[b['c']])
ch = {c: {l: v['n'][l] for l in ('it', 'fr', 'en')} for c, v in S['chapters'].items()}
for v in S['chapters'].values(): es[v['n']['en']] = v['n']['es']
groups = [{'k': g['k'], 'w': g['w'], 'n': {l: g['n'][l] for l in ('it', 'fr', 'en')}, 'c': g['c']} for g in S['groups']]
for g in S['groups']: es[g['n']['en']] = g['n']['es']
for k, v in list(es.items()):
    a = to_ar(v)
    if a and a != v: ar.setdefault(k, a)
out = {'level': S['level'], 'track': TRACK, 'exam': S['exam'], 'ch': ch, 'groups': groups, 'bank': bank, 'lessons': lessons, 'flash': flash}
if S.get('ui'): out['ui'] = {k: tri(v, 'ui') for k, v in S['ui'].items()}   # level texts of the shared study screens
js = f'/* generated by tools/spirits/build.py — do not edit */\nwindow.TWG_{N}C=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + \
     ';\nwindow.TWG_ESX=Object.assign(window.TWG_ESX||{es:{},ar:{}},{});Object.assign(window.TWG_ESX.es,' + json.dumps(es, ensure_ascii=False, separators=(',', ':')) + \
     ');Object.assign(window.TWG_ESX.ar,' + json.dumps(ar, ensure_ascii=False, separators=(',', ':')) + ');\n'
os.makedirs(f'app/{TRACK}/{LV}', exist_ok=True)
open(f'app/{TRACK}/{LV}/content.js', 'w', encoding='utf8').write(js)
h = hashlib.md5((js + open('app/l2/l2app.js', encoding='utf8').read()).encode()).hexdigest()[:8]
ix = open('app/index.html', encoding='utf8').read()
if TRACK == 'spirits': ix = re.sub(r"(spirits/'\+_L\+'/content\.js\?v=)\w+", lambda m: m.group(1) + h, ix)
else: ix = re.sub(r"(%s/%s/content\.js\?v=)\w+" % (TRACK, LV), lambda m: m.group(1) + h, ix)
ix = re.sub(r'l2/l2app\.js\?v=\w+', 'l2/l2app.js?v=' + h, ix)
open('app/index.html', 'w', encoding='utf8').write(ix)
from collections import Counter
cq, cl, cf = Counter(b['c'] for b in bank), Counter(b['c'] for b in lessons), Counter(b['c'] for b in flash)
print(len(bank), 'questions,', len(lessons), 'lessons,', len(flash), 'flashcards;', round(len(js) / 1024), 'KB')
for c in ORDER: print(' ', c, cq[c], cl[c], cf[c])
